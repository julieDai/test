"""Exact, memory-safe LHGCE encoding for one-layer identity inputs.

The released LHGCE implementation represents each node type with a dense
identity matrix and applies one relation-specific :class:`SAGEConv` after
``to_hetero``.  That representation is infeasible for the 40,888 compounds
in Ethnobotany even though the actual one-layer computation is sparse.

For an identity source matrix and a target node with degree ``k``, PyG's
``VarAggregation`` assigns every distinct one-hot neighbour ``j`` the value

    count(j) / k - (count(j) / k) ** 2.

Consequently, the aggregate can be represented exactly as a sparse
target-by-source matrix.  This module uses that matrix with the *official*
relation-specific ``lin_l`` and ``lin_r`` parameters, then applies the same
per-relation L2 normalization and relation-wise sum generated by
``to_hetero(..., aggr='sum')``.  It intentionally supports only the formal
configuration for which this equivalence is established: one SAGEConv layer,
VarAggregation, heterogeneous sum aggregation, and the official ``mul``
decoder.
"""

from __future__ import annotations

from collections import OrderedDict
from typing import Dict, Mapping, Sequence, Tuple

import torch
from torch import Tensor
from torch.nn import functional as F


EdgeType = Tuple[str, str, str]


def _relation_name(edge_type: EdgeType) -> str:
    return "__".join(edge_type)


def identity_variance_adjacency(
    edge_index: Tensor,
    n_source: int,
    n_target: int,
    *,
    dtype: torch.dtype = torch.float32,
) -> Tensor:
    """Return the exact sparse VarAggregation matrix for identity features.

    Duplicate edges are handled exactly: ``count`` is their multiplicity and
    ``k`` includes every input edge, matching PyG scatter-based aggregation.
    The returned sparse COO matrix has shape ``[n_target, n_source]``.
    """

    edge_index = edge_index.detach().to(device="cpu", dtype=torch.long)
    if edge_index.ndim != 2 or edge_index.shape[0] != 2:
        raise ValueError(
            f"edge_index must have shape [2, E], got {tuple(edge_index.shape)}"
        )
    if n_source < 1 or n_target < 1:
        raise ValueError("identity feature dimensions must be positive")
    if edge_index.numel() == 0:
        indices = torch.empty((2, 0), dtype=torch.long)
        values = torch.empty((0,), dtype=dtype)
        return torch.sparse_coo_tensor(
            indices, values, (n_target, n_source), dtype=dtype
        ).coalesce()

    source, target = edge_index
    if (
        int(source.min()) < 0
        or int(source.max()) >= n_source
        or int(target.min()) < 0
        or int(target.max()) >= n_target
    ):
        raise ValueError(
            "edge_index contains an identifier outside the declared node ranges"
        )

    flat = target * n_source + source
    unique, counts = torch.unique(flat, sorted=True, return_counts=True)
    unique_target = torch.div(unique, n_source, rounding_mode="floor")
    unique_source = unique.remainder(n_source)
    degree = torch.bincount(target, minlength=n_target).to(dtype=dtype)
    probability = counts.to(dtype=dtype) / degree[unique_target]
    values = probability - probability.square()
    indices = torch.stack((unique_target, unique_source), dim=0)
    return torch.sparse_coo_tensor(
        indices, values, (n_target, n_source), dtype=dtype
    ).coalesce()


def _relation_conv(official_model: torch.nn.Module, edge_type: EdgeType):
    return official_model.encoder.convs[0][_relation_name(edge_type)]


def materialize_official_identity_parameters(
    official_model: torch.nn.Module,
    edge_types: Sequence[EdgeType],
    node_counts: Mapping[str, int],
) -> None:
    """Materialize official lazy linears without allocating identity inputs.

    The calls follow the edge-type order used by the generated PyG graph.  A
    dense official forward initializes ``lin_l`` and then ``lin_r`` for each
    relation in exactly this order, so seeded initialization is preserved.
    """

    reference = next(official_model.linear.parameters())
    with torch.no_grad():
        for source_type, relation, target_type in edge_types:
            edge_type = (source_type, relation, target_type)
            conv = _relation_conv(official_model, edge_type)
            source_probe = torch.empty(
                (0, int(node_counts[source_type])),
                dtype=reference.dtype,
                device=reference.device,
            )
            target_probe = torch.empty(
                (0, int(node_counts[target_type])),
                dtype=reference.dtype,
                device=reference.device,
            )
            conv.lin_l(source_probe)
            conv.lin_r(target_probe)


class ExactIdentityLHGCE(torch.nn.Module):
    """Wrap the pinned official model with an exact sparse identity forward."""

    def __init__(
        self,
        official_model: torch.nn.Module,
        edge_index_dict: Mapping[EdgeType, Tensor],
        node_counts: Mapping[str, int],
        edge_types: Sequence[EdgeType],
    ) -> None:
        super().__init__()
        self.official_model = official_model
        self.node_counts = OrderedDict(
            (name, int(count)) for name, count in node_counts.items()
        )
        self.edge_types = tuple(tuple(edge_type) for edge_type in edge_types)
        self._validate_official_modules()

        reference = next(official_model.linear.parameters())
        for index, edge_type in enumerate(self.edge_types):
            source_type, _, target_type = edge_type
            adjacency = identity_variance_adjacency(
                edge_index_dict[edge_type],
                self.node_counts[source_type],
                self.node_counts[target_type],
                dtype=reference.dtype,
            )
            self.register_buffer(f"identity_variance_{index}", adjacency)

    def _validate_official_modules(self) -> None:
        if len(self.official_model.encoder.convs) != 1:
            raise ValueError("exact identity algebra supports exactly one SAGEConv layer")
        if getattr(self.official_model.linear, "aggregator", None) != "mul":
            raise ValueError("exact formal path requires the official mul decoder")

        from torch_geometric.nn.aggr import VarAggregation

        relation_modules = self.official_model.encoder.convs[0]
        for edge_type in self.edge_types:
            relation_name = _relation_name(edge_type)
            if relation_name not in relation_modules:
                raise ValueError(f"official encoder is missing relation {edge_type}")
            conv = relation_modules[relation_name]
            if not isinstance(conv.aggr_module, VarAggregation):
                raise ValueError("exact formal path requires VarAggregation")
            if not conv.normalize or not conv.root_weight or conv.project:
                raise ValueError(
                    "exact formal path requires normalize=True, root_weight=True, "
                    "and project=False"
                )

    def initialize_parameters(self) -> None:
        materialize_official_identity_parameters(
            self.official_model, self.edge_types, self.node_counts
        )

    def encode(self) -> Dict[str, Tensor]:
        incoming: Dict[str, list[Tensor]] = {
            node_type: [] for node_type in self.node_counts
        }
        for index, edge_type in enumerate(self.edge_types):
            _, _, target_type = edge_type
            conv = _relation_conv(self.official_model, edge_type)
            adjacency = getattr(self, f"identity_variance_{index}")
            if conv.lin_l.in_channels <= 0 or conv.lin_r.in_channels <= 0:
                raise RuntimeError(
                    "call initialize_parameters() before the first optimizer step"
                )

            # lin_l(A) == A @ lin_l.weight.T + bias.  The root identity term
            # is lin_r(I) == lin_r.weight.T.
            relation_output = torch.sparse.mm(
                adjacency, conv.lin_l.weight.transpose(0, 1)
            )
            if conv.lin_l.bias is not None:
                relation_output = relation_output + conv.lin_l.bias
            relation_output = relation_output + conv.lin_r.weight.transpose(0, 1)
            relation_output = F.normalize(relation_output, p=2.0, dim=-1)
            incoming[target_type].append(relation_output)

        encoded: Dict[str, Tensor] = {}
        for node_type, relation_outputs in incoming.items():
            if not relation_outputs:
                raise RuntimeError(
                    f"node type {node_type!r} has no incoming relation; "
                    "to_hetero cannot produce its representation"
                )
            value = relation_outputs[0]
            for relation_output in relation_outputs[1:]:
                value = torch.add(value, relation_output)
            encoded[node_type] = value
        return encoded

    def decode(self, encoded: Mapping[str, Tensor], edge_label_index: Tensor) -> Tensor:
        """Apply the untouched official decoder to precomputed node states.

        Keeping encoding and decoding separate lets the runner stream a large
        supervision table through the decoder while evaluating the graph
        encoder exactly once per optimizer update, as the released full-batch
        implementation does.
        """

        return self.official_model.linear(encoded, edge_label_index)

    def forward(self, edge_label_index: Tensor) -> Tensor:
        return self.decode(self.encode(), edge_label_index)


def chunked_bce_with_logits_backward(
    model: ExactIdentityLHGCE,
    edge_label_index: Tensor,
    targets: Tensor,
    *,
    pos_weight: Tensor,
    chunk_size: int,
) -> float:
    """Backpropagate the exact full-batch weighted BCE in bounded chunks.

    ``BCEWithLogitsLoss(reduction='mean')`` is the sum of the element losses
    divided by the total number of rows.  Each streamed chunk therefore uses
    ``reduction='sum' / n``.  Gradients accumulate into the same parameters,
    including the shared encoding graph, and are mathematically identical to
    one materialized full-batch loss (up to floating-point summation order).

    The caller remains responsible for zeroing gradients and stepping the
    optimizer.  This separation is useful for explicit equivalence tests.
    """

    if chunk_size < 1:
        raise ValueError("chunk_size must be positive")
    if edge_label_index.ndim != 2 or edge_label_index.shape[0] != 2:
        raise ValueError("edge_label_index must have shape [2, n]")
    if targets.ndim != 1 or edge_label_index.shape[1] != targets.numel():
        raise ValueError("targets must be one-dimensional and match the pair count")
    total = int(targets.numel())
    if total < 1:
        raise ValueError("at least one training target is required")

    encoded = model.encode()
    summed_loss = 0.0
    for start in range(0, total, chunk_size):
        stop = min(start + chunk_size, total)
        logits = model.decode(encoded, edge_label_index[:, start:stop])
        chunk_sum = F.binary_cross_entropy_with_logits(
            logits,
            targets[start:stop],
            pos_weight=pos_weight,
            reduction="sum",
        )
        (chunk_sum / total).backward(retain_graph=stop < total)
        summed_loss += float(chunk_sum.detach().cpu())
    return summed_loss / total


@torch.no_grad()
def chunked_sigmoid_scores(
    model: ExactIdentityLHGCE,
    edge_label_index: Tensor,
    *,
    chunk_size: int,
) -> Tensor:
    """Return full sigmoid scores while bounding decoder intermediates."""

    if chunk_size < 1:
        raise ValueError("chunk_size must be positive")
    if edge_label_index.ndim != 2 or edge_label_index.shape[0] != 2:
        raise ValueError("edge_label_index must have shape [2, n]")

    encoded = model.encode()
    parts = []
    total = int(edge_label_index.shape[1])
    for start in range(0, total, chunk_size):
        stop = min(start + chunk_size, total)
        logits = model.decode(encoded, edge_label_index[:, start:stop])
        parts.append(torch.sigmoid(logits).detach().cpu())
    if not parts:
        return torch.empty((0,), dtype=next(model.parameters()).dtype)
    return torch.cat(parts, dim=0)
